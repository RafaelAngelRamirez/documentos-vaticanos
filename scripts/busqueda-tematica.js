/**
 * Estantes de búsqueda temática y BM25, sin red y sin tocar el corpus.
 *
 * La regla de estante y el recorte por fuente viven aquí. El medidor
 * `scripts/medir-busqueda-tematica.mjs` repite la misma lista de familias
 * del Vaticano II para poder correr solo.
 *
 *   node scripts/busqueda-tematica.test.js
 */

'use strict';

const LOCALES = ['es', 'en', 'zh', 'hi', 'ar', 'la', 'it', 'fr', 'de', 'pt', 'el'];

/** Constituciones, decretos y declaraciones. En el corpus el kind es magisterium. */
const VATICAN_II = new Set([
  'aa',
  'ag',
  'cd',
  'dh',
  'dv',
  'ge',
  'gs',
  'im',
  'lg',
  'na',
  'ot',
  'pc',
  'po',
  'sc',
  'ur',
]);

const DEFAULT_SHELVES = [
  'catecismo',
  'codigo',
  'concilio',
  'enciclica',
  'padres',
];

/**
 * Lemas medidos. Cada forma es una clave ya plegada del índice.
 * No entra el prefijo: «comuni» arrastra comunidad y comunicación,
 * «hosti» arrastra el latín hostis.
 */
const LEMAS = {
  es: {
    eucaristia: [
      'eucaristica',
      'eucaristico',
      'eucaristicas',
      'eucaristicos',
      'eucaristias',
    ],
  },
  en: {
    eucharist: ['eucharistic'],
  },
  la: {
    eucharistia: ['eucharistiae', 'eucharisticum'],
  },
};

function foldToken(texto) {
  return String(texto || '')
    .normalize('NFD')
    .replace(
      /([^n\u0300-\u036f]|n(?!\u0303(?![\u0300-\u036f])))[\u0300-\u036f]+/gi,
      '$1',
    )
    .normalize('NFC')
    .replace(/[,".«»“”:;!¡¿?—']/gi, '')
    .replace(/[\[\]”]/gi, '')
    .replace(/[-()*\/`‘–…]/gi, '')
    .toLowerCase()
    .trim();
}

function localeOf(meta) {
  if (meta && meta.locale) {
    return String(meta.locale).toLowerCase().split(/[-_]/)[0];
  }
  const base = String((meta && meta.id) || '').replace(/-ai$/i, '');
  const match = base.match(new RegExp(`-(${LOCALES.join('|')})$`, 'i'));
  return match ? match[1].toLowerCase() : '';
}

function familyKey(meta) {
  let base = String((meta && meta.id) || '').replace(/-ai$/i, '');
  const loc = localeOf(meta);
  if (loc && base.toLowerCase().endsWith(`-${loc}`)) {
    base = base.slice(0, -(loc.length + 1));
  }
  return base;
}

function isAi(meta) {
  if (!meta) return false;
  if (/-ai$/i.test(meta.id || '')) return true;
  if (meta.translationProvenance === 'ai') return true;
  if (meta.ai === true) return true;
  const note = meta.sourceNote || '';
  return (
    /generad[oa]\s+por\s+IA/i.test(note) ||
    /generated by AI/i.test(note) ||
    /AI[- ]generated/i.test(note)
  );
}

/**
 * Estante de una ficha del manifiesto.
 * Encíclica: la URL de vatican.va, no la palabra en un motu proprio.
 * Concilio: kind council, o una familia del Vaticano II.
 */
function shelfOf(meta) {
  const url = String((meta && meta.sourceUrl) || '').toLowerCase();
  const title = String((meta && meta.title) || '').toLowerCase();
  const id = String((meta && meta.id) || '').toLowerCase();
  const kind = meta && meta.kind;
  if (kind === 'catechism') return 'catecismo';
  if (kind === 'canon-law') return 'codigo';
  if (kind === 'council' || VATICAN_II.has(familyKey(meta))) return 'concilio';
  if (kind === 'patristic') return 'padres';
  if (kind === 'bible') return 'biblia';
  if (kind === 'magisterium') {
    if (
      url.includes('/encyclicals/') ||
      url.includes('encyclical') ||
      url.includes('enciclic') ||
      /enc[ií]clica/.test(title) ||
      id.includes('enciclica')
    ) {
      return 'enciclica';
    }
    if (
      url.includes('/exhortations/') ||
      url.includes('exhortation') ||
      /exhortaci/.test(title)
    ) {
      return 'exhortacion';
    }
    return 'magisterio';
  }
  return kind || 'otro';
}

function lemasDe(term, locale) {
  const folded = foldToken(term);
  if (!folded) return [];
  const table = LEMAS[locale] || null;
  const extra = table && table[folded] ? table[folded] : [];
  return [folded, ...extra];
}

function idf(nDocs, df) {
  const n = nDocs > 0 ? nDocs : 1;
  const d = df > 0 ? df : 0;
  return Math.log(1 + (n - d + 0.5) / (d + 0.5));
}

function bm25(tf, dl, avgdl, idfVal, k1 = 1.2, b = 0.75) {
  const avg = avgdl > 0 ? avgdl : 1;
  const norm = 1 - b + b * ((dl > 0 ? dl : 1) / avg);
  const f = tf > 0 ? tf : 0;
  return (idfVal * (f * (k1 + 1))) / (f + k1 * norm);
}

function officialRank(hit) {
  if (hit.official === true) return 0;
  if (hit.official === false || hit.ai === true) return 1;
  return 0;
}

function adjustedScore(hit) {
  const base = Number(hit.score) || 0;
  if (hit.toc) return base * 0.15;
  return base;
}

/**
 * Una columna por estante.
 * Primero las ediciones oficiales, después las de estudio.
 * Como mucho `maxPerDoc` pasajes del mismo documento.
 * Un estante sin aciertos queda vacío: no se rellena con otro.
 */
function columnasPorEstante(hits, opts = {}) {
  const maxPerDoc = opts.maxPerDoc == null ? 2 : opts.maxPerDoc;
  const maxPerShelf = opts.maxPerShelf == null ? 3 : opts.maxPerShelf;
  const shelves = opts.shelves || DEFAULT_SHELVES;
  const by = new Map(shelves.map((s) => [s, []]));
  for (const hit of hits || []) {
    if (!hit || !by.has(hit.shelf)) continue;
    by.get(hit.shelf).push(hit);
  }
  const out = {};
  for (const shelf of shelves) {
    const raw = by.get(shelf);
    const usable = raw.some((h) => !h.toc) ? raw.filter((h) => !h.toc) : raw;
    const ranked = usable.slice().sort((a, b) => {
      const ao = officialRank(a);
      const bo = officialRank(b);
      if (ao !== bo) return ao - bo;
      const as = adjustedScore(a);
      const bs = adjustedScore(b);
      if (bs !== as) return bs - as;
      const id = String(a.documentId || '').localeCompare(String(b.documentId || ''));
      if (id !== 0) return id;
      return (a.unitIndex || 0) - (b.unitIndex || 0);
    });
    const seen = new Map();
    const picked = [];
    for (const hit of ranked) {
      const id = hit.documentId || '';
      const n = seen.get(id) || 0;
      if (n >= maxPerDoc) continue;
      seen.set(id, n + 1);
      picked.push(hit);
      if (picked.length >= maxPerShelf) break;
    }
    out[shelf] = picked;
  }
  return out;
}

module.exports = {
  VATICAN_II,
  DEFAULT_SHELVES,
  LEMAS,
  foldToken,
  localeOf,
  familyKey,
  isAi,
  shelfOf,
  lemasDe,
  idf,
  bm25,
  columnasPorEstante,
};
